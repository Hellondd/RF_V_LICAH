def load_regions():
    db = SessionLocal()
    
    created = 0
    skipped = 0
    
    for region_data in REGIONS:
        existing = db.query(Region).filter(Region.title == region_data['title']).first()
        
        if existing:
            print(f"⏭️  Пропускаем (уже есть): {region_data['title']}")
            skipped += 1
            continue
        
        region = Region(
            title=region_data['title'],
            federal_district=region_data['federal_district'],
            capital=region_data['capital'],
            short_description=f"Регион {region_data['title']}",
            full_description=f"Подробная информация о регионе {region_data['title']}",
            facts=[],
            culture="",
            achievements="",
            image_url=None
        )
        
        db.add(region)
        created += 1
        print(f"✅ Добавлен: {region_data['title']}")
    
    db.commit()
    db.close()
    
    print(f"\n🎉 Готово!")
    print(f"   ✅ Создано: {created}")
    print(f"   ⏭️  Пропущено: {skipped}")

if __name__ == "__main__":
    load_regions()